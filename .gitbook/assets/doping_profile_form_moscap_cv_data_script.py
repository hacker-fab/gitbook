def validate_datasets(dataset_cfgs):
    if len(dataset_cfgs) == 0:
        raise ValueError('DATASETS is empty.')

    labels = [dataset_label_from_config(cfg) for cfg in dataset_cfgs]
    if len(labels) != len(set(labels)):
        raise ValueError('Dataset labels must be unique. Change the label field or folder names.')

    for cfg in dataset_cfgs:
        if 'folder' not in cfg:
            raise ValueError('Each dataset config needs a folder key.')
        if 'size_to_compare' not in cfg:
            raise ValueError('Each dataset config needs a size_to_compare key.')
        if cfg['size_to_compare'] not in ['Small', 'Medium', 'Large']:
            raise ValueError(f"Unsupported size_to_compare: {cfg['size_to_compare']}")
        if 'area_mm2' not in cfg:
            raise ValueError('Each dataset config needs area_mm2 for doping extraction.')
        if not np.isfinite(cfg['area_mm2']) or cfg['area_mm2'] <= 0:
            raise ValueError('area_mm2 must be finite and > 0 for doping extraction.')


def main():
    validate_datasets(DATASETS)

    all_curves = []
    for cfg in DATASETS:
        curves = collect_curves_for_dataset(cfg)
        all_curves.extend(curves)
        print(f'Collected {len(curves)} usable curves from {dataset_label_from_config(cfg)}')

    if len(all_curves) == 0:
        print('No usable curves were found.')
        return

    grouped_raw = group_curves(all_curves, 'capacitance', ['dataset_label', 'direction'])
    grouped_corr = group_curves(all_curves, 'capacitance_corrected', ['dataset_label', 'direction'])

    inv_metric = 'inverse_c2_corrected' if DOPING_USE_CORRECTED_CAP else 'inverse_c2'
    grouped_inv_c2 = group_curves(all_curves, inv_metric, ['dataset_label', 'direction'])

    plot_avg_raw_cv(grouped_raw, DATASETS)
    plot_avg_and_corrected_cv(grouped_raw, grouped_corr, DATASETS)
    plot_avg_inverse_c2_with_fit(grouped_inv_c2, DATASETS)
    if PLOT_COMBINED_CORRECTED_C_AND_INVC2:
        plot_combined_corrected_cv_and_inverse_c2(
            grouped_corr, grouped_inv_c2, DATASETS
        )
    build_doping_summary(grouped_inv_c2, DATASETS)

    print('\nDone.')
    print('\nNotes:')
    print('- Doping is extracted from the fitted slope of 1/C^2 vs V.')
    print('- Positive slope implies acceptors (p-type); negative slope implies donors (n-type).')
    print('- Adjust DOPING_FIT_VMIN and DOPING_FIT_VMAX so the fit covers only the linear depletion region.')
    print('- Compare PN and NP results; if they disagree, trust the cleaner linear fit / higher R^2.')

if __name__ == '__main__':
    main()

