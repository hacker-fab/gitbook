def plot_combined_corrected_cv_and_inverse_c2(grouped_corr, grouped_inv_c2, dataset_cfgs):
    """
    Plot corrected capacitance and 1/C^2 against the same voltage axis.

    Corrected capacitance uses the left y-axis, while 1/C^2 and its linear
    doping fit use the right y-axis. Each y-axis label, ticks, spine, and
    corresponding curves share the same color so the association is clear.
    """
    fig, ax_c = plt.subplots(figsize=COMBINED_FIGSIZE)
    ax_inv = ax_c.twinx()

    c_xy_pairs = []
    inv_xy_pairs = []
    curve_handles = []

    # The same voltage interval is used for the fit and concentration extraction.
    ax_c.axvspan(
        DOPING_FIT_VMIN,
        DOPING_FIT_VMAX,
        color=COMBINED_FIT_REGION_COLOR,
        alpha=COMBINED_FIT_REGION_ALPHA,
        zorder=0,
    )

    for cfg_index, cfg in enumerate(dataset_cfgs):
        label = dataset_label_from_config(cfg)
        area_mm2 = cfg.get('area_mm2', np.nan)

        # Slightly reduce alpha for later datasets while preserving the
        # metric-specific axis colors.
        dataset_alpha = max(0.45, 1.0 - 0.12 * cfg_index)

        for direction in ['PN', 'NP']:
            key = (label, direction)
            marker = DIRECTION_MARKERS[direction]
            linestyle = DIRECTION_LINESTYLES[direction]

            if key in grouped_corr:
                item_c = grouped_corr[key]
                x_c = np.asarray(item_c['voltage'], dtype=float)
                y_c = np.asarray(item_c['mean'], dtype=float)

                ax_c.plot(
                    x_c,
                    y_c,
                    color=COMBINED_C_AXIS_COLOR,
                    marker=marker,
                    linestyle=linestyle,
                    markersize=3,
                    linewidth=CORRECTED_LINEWIDTH,
                    alpha=dataset_alpha,
                    zorder=3,
                )
                c_xy_pairs.append((x_c, y_c))

                curve_handles.append(
                    Line2D(
                        [0], [0],
                        color=COMBINED_C_AXIS_COLOR,
                        marker=marker,
                        linestyle=linestyle,
                        linewidth=CORRECTED_LINEWIDTH,
                        markersize=6,
                        alpha=dataset_alpha,
                        label=f'{label} - {direction} - corrected C',
                    )
                )

            if key not in grouped_inv_c2:
                continue

            item_inv = grouped_inv_c2[key]
            x_inv = np.asarray(item_inv['voltage'], dtype=float)
            y_inv = np.asarray(item_inv['mean'], dtype=float)

            ax_inv.plot(
                x_inv,
                y_inv,
                color=COMBINED_INVC2_AXIS_COLOR,
                marker=marker,
                linestyle=linestyle,
                markersize=3,
                linewidth=2,
                alpha=dataset_alpha,
                zorder=4,
            )
            inv_xy_pairs.append((x_inv, y_inv))

            curve_handles.append(
                Line2D(
                    [0], [0],
                    color=COMBINED_INVC2_AXIS_COLOR,
                    marker=marker,
                    linestyle=linestyle,
                    linewidth=2,
                    markersize=6,
                    alpha=dataset_alpha,
                    label=f'{label} - {direction} - 1/C²',
                )
            )

            fit = fit_inverse_c2_line(
                item_inv['voltage'],
                item_inv['mean'],
                area_mm2,
                DOPING_FIT_VMIN,
                DOPING_FIT_VMAX,
            )

            if COMBINED_SHOW_BEST_FIT_LINE and np.isfinite(fit['slope']):
                ax_inv.plot(
                    fit['x_line'],
                    fit['y_line'],
                    color=COMBINED_INVC2_AXIS_COLOR,
                    linestyle=linestyle,
                    linewidth=3.2,
                    alpha=dataset_alpha,
                    zorder=5,
                )
                inv_xy_pairs.append((fit['x_line'], fit['y_line']))

                if COMBINED_LABEL_DOPING_FIT_LINES and LABEL_DOPING_FIT_LINES:
                    fit_label = format_doping_fit_label(fit)
