def build_doping_summary(grouped_inv_c2, dataset_cfgs):
    rows = []

    for cfg in dataset_cfgs:
        label = dataset_label_from_config(cfg)
        area_mm2 = cfg.get('area_mm2', np.nan)

        row = {
            'folder': label,
            'size': cfg.get('size_to_compare', ''),
            'area_mm2': area_mm2,
            'frequency': TARGET_FREQUENCY,
            'fit_Vmin': DOPING_FIT_VMIN,
            'fit_Vmax': DOPING_FIT_VMAX,
            'cap_used': 'corrected' if DOPING_USE_CORRECTED_CAP else 'raw',
        }

        doping_vals = []
        type_vals = []

        for direction in ['PN', 'NP']:
            key = (label, direction)

            if key not in grouped_inv_c2:
                row[f'npts_fit_{direction}'] = 0
                row[f'slope_{direction}'] = np.nan
                row[f'R2_{direction}'] = np.nan
                row[f'type_{direction}'] = ''
                row[f'N_{direction}_cm^-3'] = np.nan
                continue

            item = grouped_inv_c2[key]
            fit = fit_inverse_c2_line(
                item['voltage'],
                item['mean'],
                area_mm2,
                DOPING_FIT_VMIN,
                DOPING_FIT_VMAX
            )

            row[f'npts_fit_{direction}'] = fit['npts']
            row[f'slope_{direction}'] = fit['slope']
            row[f'R2_{direction}'] = fit['r2']
            row[f'type_{direction}'] = fit['carrier_type']
            row[f'N_{direction}_cm^-3'] = fit['doping_cm3_abs']

            if np.isfinite(fit['doping_cm3_abs']):
                doping_vals.append(fit['doping_cm3_abs'])
            if fit['carrier_type'] != 'unknown':
                type_vals.append(fit['carrier_type'])

        row['N_mean_cm^-3'] = np.nanmean(doping_vals) if len(doping_vals) else np.nan

        unique_types = list(dict.fromkeys(type_vals))
        if len(unique_types) == 1:
            row['type_consensus'] = unique_types[0]
        elif len(unique_types) > 1:
            row['type_consensus'] = 'mixed / check fit window'
        else:
            row['type_consensus'] = 'unknown'

        rows.append(row)

    summary = pd.DataFrame(rows)

    display_cols = [
        'folder',
        'size',
        'area_mm2',
        'frequency',
        'cap_used',
        'fit_Vmin',
        'fit_Vmax',
        'npts_fit_PN',
        'slope_PN',
        'R2_PN',
        'type_PN',
        'N_PN_cm^-3',
        'npts_fit_NP',
        'slope_NP',
        'R2_NP',
        'type_NP',
        'N_NP_cm^-3',
        'type_consensus',
        'N_mean_cm^-3',
    ]
    display_cols = [c for c in display_cols if c in summary.columns]
    summary_display = summary[display_cols].copy()

    print('\nDoping extraction summary:')
    print(summary_display.to_string(index=False))

    fig_width = max(18, 0.9 * len(summary_display.columns))
    fig_height = max(3.0, 1.0 + 0.35 * len(summary_display))
    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    ax.axis('off')

    disp = summary_display.copy()
    for col in disp.columns:
        if col in ['folder', 'size', 'frequency', 'cap_used', 'type_PN', 'type_NP', 'type_consensus']:
            continue
        disp[col] = disp[col].apply(lambda x: f'{x:.4g}' if pd.notnull(x) and np.isfinite(x) else '')

    tbl = ax.table(
        cellText=disp.values,
        colLabels=disp.columns,
        loc='center'
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(8)
    tbl.scale(1, 1.35)
    show_plot(fig)

    return summary


