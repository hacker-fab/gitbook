def _is_number(x):
    return x is not None and np.isfinite(x)


def _manual_or_auto_ylim_from_visible_x(
    ax,
    xy_pairs,
    use_manual_ylim=False,
    ymin=None,
    ymax=None,
    auto_ylim_to_xlim=True,
    padding_fraction=0.08,
):
    """
    Fix Matplotlib's default behavior where y autoscaling still includes
    data outside a manually-set x-axis window.

    Parameters
    ----------
    ax : matplotlib axis
    xy_pairs : list of (x_array, y_array)
        The plotted x/y data that should be considered for y-axis scaling.
        Include upper/lower fill_between bounds if those should stay visible.
    use_manual_ylim : bool
        If True, manual ymin/ymax are applied and auto-scaling is skipped.
    ymin, ymax : float or None
        Manual y limits. If only one is provided, the other side uses the
        current Matplotlib limit.
    auto_ylim_to_xlim : bool
        If True and CV_USE_XLIM is True, compute y limits using only points
        with CV_XMIN <= x <= CV_XMAX.
    padding_fraction : float
        Fractional padding added above/below the visible y range.
    """
    if use_manual_ylim:
        current_ymin, current_ymax = ax.get_ylim()
        ax.set_ylim(
            ymin if _is_number(ymin) else current_ymin,
            ymax if _is_number(ymax) else current_ymax,
        )
        return

    if not (auto_ylim_to_xlim and CV_USE_XLIM):
        return

    visible_y_values = []

    for x, y in xy_pairs:
        x = np.asarray(x, dtype=float)
        y = np.asarray(y, dtype=float)

        good = np.isfinite(x) & np.isfinite(y) & (x >= CV_XMIN) & (x <= CV_XMAX)
        if np.any(good):
            visible_y_values.append(y[good])

    if len(visible_y_values) == 0:
        return

    y_all = np.concatenate(visible_y_values)
    y_all = y_all[np.isfinite(y_all)]

    if len(y_all) == 0:
        return

    y_min = np.nanmin(y_all)
    y_max = np.nanmax(y_all)

    if not (np.isfinite(y_min) and np.isfinite(y_max)):
        return

    y_span = y_max - y_min
    if y_span <= 0:
        # Create a small, sensible window around a flat trace.
        center = y_min
        y_span = abs(center) * 0.10 if center != 0 else 1.0
        y_min = center - 0.5 * y_span
        y_max = center + 0.5 * y_span

    pad = padding_fraction * y_span
    ax.set_ylim(y_min - pad, y_max + pad)


