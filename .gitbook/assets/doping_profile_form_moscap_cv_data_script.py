def calcSeriesResAdjC(C, G, f):
    """
    Series-resistance correction for measured parallel capacitance.
    """
    C = np.asarray(C, dtype=float)
    G = np.asarray(G, dtype=float)
    f = np.asarray(f, dtype=float)

    with np.errstate(divide='ignore', invalid='ignore'):
        denom = (1 + (G / (2 * math.pi * f * C))**2) * G
        Rs = ((G / (2 * math.pi * f * C))**2) / denom
        alpha = G - (G**2 + (2 * math.pi * f * C)**2) * Rs
        C_adj = (((G**2) + (2 * math.pi * f * C)**2) * C) / (alpha**2 + (2 * math.pi * f * C)**2)

    C_adj = np.where(np.isfinite(C_adj), C_adj, np.nan)
    return C_adj


def compute_inverse_c2(capacitance):
    c = np.asarray(capacitance, dtype=float)
    out = np.full_like(c, np.nan, dtype=float)
    mask = np.isfinite(c) & (c > 0)
    out[mask] = 1.0 / (c[mask] ** 2)
    return out


def makeCommonVoltageGrid(curves, step):
    xmin = max(np.nanmin(curve['voltage']) for curve in curves)
    xmax = min(np.nanmax(curve['voltage']) for curve in curves)
    if xmax <= xmin:
        return None
    return np.arange(xmin, xmax + step / 2, step)


def average_duplicate_x(x, y):
    df = pd.DataFrame({'x': x, 'y': y}).dropna()
    if len(df) < 2:
        return None, None
    df = df.groupby('x', as_index=False)['y'].mean().sort_values('x')
    return df['x'].to_numpy(), df['y'].to_numpy()


def interpolateCurveToGrid(x, y, common_grid):
    x2, y2 = average_duplicate_x(x, y)
    if x2 is None or len(x2) < 2:
        return None
    return np.interp(common_grid, x2, y2)


