"""
MOSCAP C-V comparison + substrate doping extraction
using the 1/C^2 vs V method

Based on the earlier MOSCAP comparison script, but stripped down and
re-focused for substrate doping extraction.

What this script does
---------------------
1. Loads MOSCAP C-V data from multiple folders
2. Averages repeated curves within each folder / sweep direction
3. Optionally applies series-resistance correction
4. Plots:
   - averaged raw C-V
   - averaged raw + corrected C-V
   - averaged 1/C^2 vs V with linear fit in a user-defined depletion window
5. Extracts substrate doping from the fitted 1/C^2 slope

Method used
-----------
N_sub = 2 / ( q * eps_s * A^2 * d(1/C^2)/dV )

Units:
- C in F
- A in cm^2
- eps_s in F/cm
- V in V
- N_sub comes out in cm^-3

Sign convention:
- positive slope  -> acceptors (p-type)
- negative slope  -> donors (n-type)

Important:
----------
Choose the fit window so it covers the approximately linear depletion region
only. Do not fit accumulation or deep inversion.
"""

