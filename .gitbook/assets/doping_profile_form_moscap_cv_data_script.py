def format_doping_fit_label(fit):
    """Return a Matplotlib label containing dopant type and concentration."""
    doping = fit.get('doping_cm3_abs', np.nan)
    slope = fit.get('slope', np.nan)

    if not (np.isfinite(doping) and doping > 0 and np.isfinite(slope)):
        return None

    if slope > 0:
        type_text = 'p-type (acceptor)'
        concentration_symbol = r'N_A'
    elif slope < 0:
        type_text = 'n-type (donor)'
        concentration_symbol = r'N_D'
    else:
        return None

    exponent = int(np.floor(np.log10(doping)))
    mantissa = doping / (10 ** exponent)
    concentration_text = (
        rf'${concentration_symbol} = '
        rf'{mantissa:.{DOPING_FIT_LABEL_DECIMAL_PLACES}f}'
        rf'\times 10^{{{exponent}}}\ \mathrm{{cm}}^{{-3}}$'
    )

    label = f'{type_text}\n{concentration_text}'

    if DOPING_FIT_LABEL_SHOW_R2 and np.isfinite(fit.get('r2', np.nan)):
        label += rf'\n$R^2 = {fit["r2"]:.3f}$'

    return label


def fit_inverse_c2_line(voltage, inv_c2, area_mm2, vmin, vmax):
    x = np.asarray(voltage, dtype=float)
    y = np.asarray(inv_c2, dtype=float)

    mask = np.isfinite(x) & np.isfinite(y) & (x >= vmin) & (x <= vmax)
    x_fit = x[mask]
    y_fit = y[mask]

    if len(x_fit) < DOPING_MIN_FIT_POINTS:
        return {
            'npts': len(x_fit),
            'slope': np.nan,
            'intercept': np.nan,
            'r2': np.nan,
            'x_fit': x_fit,
            'y_fit': y_fit,
            'x_line': np.array([]),
            'y_line': np.array([]),
            'doping_cm3_signed': np.nan,
            'doping_cm3_abs': np.nan,
            'carrier_type': 'unknown',
        }

    slope, intercept = np.polyfit(x_fit, y_fit, 1)
    y_pred = slope * x_fit + intercept

    ss_res = np.sum((y_fit - y_pred) ** 2)
    ss_tot = np.sum((y_fit - np.mean(y_fit)) ** 2)
    r2 = np.nan if ss_tot <= 0 else 1 - (ss_res / ss_tot)

    area_cm2 = area_mm2 * 0.01  # 1 mm^2 = 0.01 cm^2

    if (not np.isfinite(area_cm2)) or area_cm2 <= 0 or (not np.isfinite(slope)) or slope == 0:
        doping_signed = np.nan
    else:
        doping_signed = 2.0 / (Q_E * EPS_SI_F_PER_CM * (area_cm2 ** 2) * slope)

    if np.isfinite(slope):
        if slope > 0:
            carrier_type = 'acceptors (p-type)'
        elif slope < 0:
            carrier_type = 'donors (n-type)'
        else:
            carrier_type = 'unknown'
    else:
        carrier_type = 'unknown'

    x_line = np.linspace(vmin, vmax, 200)
    y_line = slope * x_line + intercept if np.isfinite(slope) and np.isfinite(intercept) else np.full_like(x_line, np.nan)

    return {
        'npts': len(x_fit),
        'slope': slope,
        'intercept': intercept,
        'r2': r2,
        'x_fit': x_fit,
        'y_fit': y_fit,
        'x_line': x_line,
        'y_line': y_line,
        'doping_cm3_signed': doping_signed,
        'doping_cm3_abs': abs(doping_signed) if np.isfinite(doping_signed) else np.nan,
        'carrier_type': carrier_type,
    }


