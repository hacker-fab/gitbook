def collect_curves_for_dataset(cfg):
    folder = cfg['folder']
    size_to_compare = cfg['size_to_compare']
    dataset_label = dataset_label_from_config(cfg)

    all_curves = []

    if not os.path.isdir(folder):
        print(f"Skipping missing folder: {folder}")
        return all_curves

    for subfolder in os.listdir(folder):
        subfolder_path = os.path.join(folder, subfolder)
        if not (os.path.isdir(subfolder_path) and subfolder == size_to_compare):
            continue

        for filename in os.listdir(subfolder_path):
            appends_to_include = filenameShouldBePlotted(filename)
            if appends_to_include is False:
                continue

            frequency, direction = extractConditionFromFilename(filename)
            if frequency != TARGET_FREQUENCY:
                continue

            sheet = os.path.join(subfolder_path, filename)
            try:
                xls = pd.ExcelFile(sheet)
            except Exception as e:
                print(f"Skipping unreadable file: {sheet} ({e})")
                continue

            for tab in xls.sheet_names:
                if not tabShouldBePlotted(tab, appends_to_include):
                    continue

                try:
                    df = pd.read_excel(sheet, tab)
                except Exception as e:
                    print(f"Skipping unreadable tab: {sheet} | {tab} ({e})")
                    continue

                needed = ['DCV_GB', 'Cp_GB', 'Gp_GB']
                if not all(col in df.columns for col in needed):
                    continue

                temp = df[['DCV_GB', 'Cp_GB', 'Gp_GB']].copy()
                if 'F_GB' in df.columns:
                    temp['F_GB'] = pd.to_numeric(df['F_GB'], errors='coerce')
                else:
                    temp['F_GB'] = np.nan

                temp = temp.apply(pd.to_numeric, errors='coerce').dropna(subset=['DCV_GB', 'Cp_GB', 'Gp_GB'])
                if len(temp) < MIN_POINTS_REQUIRED:
                    continue

                voltage = temp['DCV_GB'].to_numpy(dtype=float)
                capacitance = temp['Cp_GB'].to_numpy(dtype=float)
                conductance = temp['Gp_GB'].to_numpy(dtype=float)
                freq_from_col = temp['F_GB'].to_numpy(dtype=float)

                if np.all(~np.isfinite(freq_from_col)):
                    freq_array = safe_frequency_array_from_label(frequency, len(voltage))
                else:
                    valid = freq_from_col[np.isfinite(freq_from_col)]
                    medf = np.median(valid) if len(valid) else np.nan
                    freq_array = np.where(np.isfinite(freq_from_col), freq_from_col, medf)

                if APPLY_SERIES_CORRECTION:
                    capacitance_corrected = calcSeriesResAdjC(capacitance, conductance, freq_array)
                else:
                    capacitance_corrected = capacitance.copy()

                inv_c2_raw = compute_inverse_c2(capacitance)
                inv_c2_corr = compute_inverse_c2(capacitance_corrected)

                all_curves.append({
                    'dataset_label': dataset_label,
                    'folder': folder,
                    'size': size_to_compare,
                    'frequency': frequency,
                    'direction': direction,
                    'filename': filename,
                    'tab': tab,
                    'voltage': voltage,
                    'capacitance': capacitance,
                    'capacitance_corrected': capacitance_corrected,
                    'inverse_c2': inv_c2_raw,
                    'inverse_c2_corrected': inv_c2_corr,
                    'area_mm2': cfg.get('area_mm2', np.nan),
                })

    return all_curves


def group_curves(curves, metric_key, group_keys):
    grouped = {}
    for curve in curves:
        key = tuple(curve[k] for k in group_keys)
        grouped.setdefault(key, []).append(curve)

    results = {}
    for key, members in grouped.items():
        common_grid = makeCommonVoltageGrid(members, COMMON_VOLTAGE_STEP)
        if common_grid is None or len(common_grid) < MIN_POINTS_REQUIRED:
            continue

        arrs = []
        for curve in members:
            interp_y = interpolateCurveToGrid(curve['voltage'], curve[metric_key], common_grid)
            if interp_y is not None:
                arrs.append(interp_y)

        if len(arrs) == 0:
            continue

        arrs = np.vstack(arrs)
        results[key] = {
            'voltage': common_grid,
            'mean': np.nanmean(arrs, axis=0),
            'std': np.nanstd(arrs, axis=0),
            'n': arrs.shape[0],
            'members': members,
        }

    return results


