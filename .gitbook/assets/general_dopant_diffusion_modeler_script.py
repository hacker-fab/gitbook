def simulate_process(x_cm, engine, process, background_dopant, background_conc_cm3):
    """Simulate one independently defined diffusion process."""
    name = process.get("name", "Unnamed process")
    steps = process.get("steps", [])
    if not isinstance(steps, list) or len(steps) == 0:
        raise ValueError(f"Process '{name}' must contain at least one step")

    if engine == "analytic":
        history = build_history_analytic(
            x_cm, steps, background_dopant, background_conc_cm3
        )
    else:
        history = build_history_numeric(
            x_cm, steps, background_dopant, background_conc_cm3
        )

    final = history[-1]
    ND = ACTIVATION_PHOSPHORUS * final["phosphorus"]
    NA = ACTIVATION_BORON * final["boron"]

    xj_cm, surface_polarity = first_junction_depth_cm(x_cm, ND, NA)
    if xj_cm is None:
        x_end_cm = WAFER_THICKNESS_UM * 1e-4
        integration_basis = "wafer thickness"
    else:
        x_end_cm = xj_cm
        integration_basis = "junction depth"

    donor_dose_cm2 = integrate_to_depth(x_cm, ND, x_end_cm)
    acceptor_dose_cm2 = integrate_to_depth(x_cm, NA, x_end_cm)
    background_uniform_dose_cm2 = background_conc_cm3 * x_end_cm

    Rs, Gsheet, carrier_dose, mu_eff = compute_sheet_resistance(
        x_cm, ND, NA, x_end_cm, surface_polarity
    )

    return {
        "name": name,
        "steps": steps,
        "history": history,
        "ND": ND,
        "NA": NA,
        "xj_cm": xj_cm,
        "surface_polarity": surface_polarity,
        "x_end_cm": x_end_cm,
        "integration_basis": integration_basis,
        "donor_dose_cm2": donor_dose_cm2,
        "acceptor_dose_cm2": acceptor_dose_cm2,
        "background_uniform_dose_cm2": background_uniform_dose_cm2,
        "Rs": Rs,
        "Gsheet": Gsheet,
        "carrier_dose": carrier_dose,
        "mu_eff": mu_eff,
    }

def plot_profile(ax, x_um, y_cm3, label, color, alpha=1.0, linestyle="-", linewidth=2.0):
    if USE_LOG_Y:
        line, = ax.semilogy(
            x_um, y_cm3,
            label=label,
            color=color,
            alpha=alpha,
            linestyle=linestyle,
            linewidth=linewidth
        )
    else:
        line, = ax.plot(
            x_um, y_cm3,
            label=label,
            color=color,
            alpha=alpha,
            linestyle=linestyle,
            linewidth=linewidth
        )
    return line

def apply_axis_limits(ax):
    ax.set_xlim(0.0, PLOT_XMAX_UM)
    if YMIN_CM3 is not None or YMAX_CM3 is not None:
        ax.set_ylim(bottom=YMIN_CM3, top=YMAX_CM3)

