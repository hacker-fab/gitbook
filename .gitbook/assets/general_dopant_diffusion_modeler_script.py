def main():
    bg = BACKGROUND_DOPANT.strip().lower()
    if bg not in ("boron", "phosphorus"):
        raise ValueError("BACKGROUND_DOPANT must be 'boron' or 'phosphorus'")

    engine = DIFFUSION_ENGINE.strip().lower()
    if engine not in ("analytic", "numeric"):
        raise ValueError("DIFFUSION_ENGINE must be 'analytic' or 'numeric'")

    if not isinstance(PROCESSES, list) or len(PROCESSES) == 0:
        raise ValueError("PROCESSES must contain at least one process dictionary")

    x_cm, x_um = make_x_grid(engine, WAFER_THICKNESS_UM)
    results = [
        simulate_process(
            x_cm,
            engine,
            process,
            bg,
            BACKGROUND_CONCENTRATION_CM3,
        )
        for process in PROCESSES
    ]

    print("\n" + "=" * 88)
    print("DIFFUSION PROCESS COMPARISON SUMMARY")
    print("=" * 88)
    print(f"Background dopant                         : {BACKGROUND_DOPANT}")
    print(f"Background concentration                  : {format_sci(BACKGROUND_CONCENTRATION_CM3)} cm^-3")
    print(f"Wafer thickness                           : {WAFER_THICKNESS_UM:.3f} um")
    print(f"Number of compared processes              : {len(results)}")

    for process_index, result in enumerate(results, start=1):
        print("\n" + "-" * 88)
        print(f"PROCESS {process_index}: {result['name']}")
        print("-" * 88)
        print(f"Number of programmed steps                : {len(result['steps'])}")

        print("\nProgrammed steps")
        for step_index, step in enumerate(result["steps"], start=1):
            source = step.get("source_dopant", None)
            if source is None:
                print(
                    f"  {step_index}. {step['name']}: drive-in, "
                    f"T={step['temp_C']} C, t={step['time_min']} min"
                )
            else:
                print(
                    f"  {step_index}. {step['name']}: {source} predep, "
                    f"Cs={format_sci(step['surface_concentration_cm3'])} cm^-3, "
                    f"T={step['temp_C']} C, t={step['time_min']} min"
                )

        print("\nFinal surface concentrations")
        print(f"  Final phosphorus at x=0                 : {format_sci(result['ND'][0])} cm^-3")
        print(f"  Final boron at x=0                      : {format_sci(result['NA'][0])} cm^-3")
        print(f"  Surface polarity                        : {result['surface_polarity']}")

        print("\nIntegration depth used for dose / electrical model")
        if result["xj_cm"] is None:
            print(f"  No junction found; using wafer thickness: {WAFER_THICKNESS_UM:.4f} um")
        else:
            print(f"  Junction depth xj                       : {result['xj_cm'] * 1e4:.4f} um")
            print("  Using x = 0 to x = xj")

        print("\nIntegrated doses over the chosen depth")
        print(f"  Donor dose                              : {format_sci(result['donor_dose_cm2'])} cm^-2")
        print(f"  Acceptor dose                           : {format_sci(result['acceptor_dose_cm2'])} cm^-2")
        print(f"  Uniform background dose over same depth : {format_sci(result['background_uniform_dose_cm2'])} cm^-2")
        print(f"  Majority-carrier dose                   : {format_sci(result['carrier_dose'])} cm^-2")

        print("\nElectrical result")
        print(f"  Sheet conductance                       : {format_sci(result['Gsheet'])} S/sq")
        if SHOW_RS:
            rs_text = "None" if result["Rs"] is None else f"{result['Rs']:.4g} ohm/sq"
            print(f"  Expected Rs                             : {rs_text}")
        mu_text = "None" if result["mu_eff"] is None else f"{result['mu_eff']:.4g} cm^2/Vs"
        print(f"  Effective average mobility              : {mu_text}")
        print(f"  Mobility model                          : {MOBILITY_MODEL}")

    # ---------------- Plot ----------------
    fig, ax = plt.subplots(figsize=(11.5, 7.0), constrained_layout=True)

    for process_index, result in enumerate(results):
        process_name = result["name"]
        process_style = PROCESS_LINESTYLES[process_index % len(PROCESS_LINESTYLES)]
        history = result["history"]

        if SHOW_INTERMEDIATE_STEPS and len(history) > 2:
            n_mid = len(history) - 2
            for step_number, item in enumerate(history[1:-1], start=1):
                alpha = 0.08 + 0.22 * (step_number / max(n_mid, 1))
                P = ACTIVATION_PHOSPHORUS * item["phosphorus"]
                B = ACTIVATION_BORON * item["boron"]

                if np.max(P) > 0:
                    plot_profile(
                        ax, x_um, P, "_nolegend_", COLOR_PHOSPHORUS,
                        alpha=alpha, linestyle=process_style, linewidth=1.0
                    )
                if np.max(B) > 0:
                    plot_profile(
                        ax, x_um, B, "_nolegend_", COLOR_BORON,
                        alpha=alpha, linestyle=process_style, linewidth=1.0
                    )

        if np.max(result["ND"]) > 0:
            plot_profile(
                ax,
                x_um,
                result["ND"],
                f"{process_name} - phosphorus",
                COLOR_PHOSPHORUS,
                alpha=1.0,
                linestyle=process_style,
                linewidth=2.8,
            )

        if np.max(result["NA"]) > 0:
            plot_profile(
                ax,
                x_um,
                result["NA"],
                f"{process_name} - boron",
                COLOR_BORON,
                alpha=1.0,
                linestyle=process_style,
                linewidth=2.3,
            )

        if result["xj_cm"] is not None:
            ax.axvline(
                result["xj_cm"] * 1e4,
                color=COLOR_JUNCTION,
                linestyle=process_style,
                linewidth=1.5,
                alpha=0.75,
            )

    add_results_summary_box(ax, build_results_summary_lines(results))

    if SHOW_PROCESS_SUMMARY_BOX:
        process_summary_lines = build_process_summary_lines(
            PROCESSES, bg, BACKGROUND_CONCENTRATION_CM3
        )
        add_process_summary_box(ax, process_summary_lines)

    ax.set_title(PLOT_TITLE)
    ax.set_xlabel("Depth into Si (um)")
    ax.set_ylabel("Concentration (cm$^{-3}$)")
    ax.grid(True, which="both", alpha=0.3)
    apply_axis_limits(ax)
    ax.legend(fontsize=8, loc="upper left")
    plt.show()


if __name__ == "__main__":
    main()