def diffusivity_cm2_s(dopant_name, T_C):
    dop = DOPANT_DATABASE[dopant_name.lower()]
    D0 = dop["D0_cm2_per_s"]
    Ea = dop["Ea_eV"]
    T_K = T_C + 273.15
    return D0 * np.exp(-Ea / (K_B_EV_PER_K * T_K))

def erfc_array(x):
    return np.vectorize(math.erfc)(x)

def predep_erfc_profile_cm3(x_cm, Cs_cm3, D_cm2_s, t_s):
    if D_cm2_s <= 0 or t_s <= 0:
        return np.zeros_like(x_cm)
    return Cs_cm3 * erfc_array(x_cm / (2.0 * np.sqrt(D_cm2_s * t_s)))

def gaussian_from_predep_cm3(x_cm, Cs_pre_cm3, D_pre_cm2_s, t_pre_s, L_drive_cm2):
    """
    Convert one earlier predep into a Gaussian after later redistribution.

    Q = 2 * Cs * sqrt(D_pre * t_pre / pi)

    C(x) = Q / sqrt(pi * L_drive) * exp(-x^2 / (4 L_drive))
    """
    if D_pre_cm2_s <= 0 or t_pre_s <= 0 or L_drive_cm2 <= 0:
        return np.zeros_like(x_cm)

    Q = 2.0 * Cs_pre_cm3 * np.sqrt(D_pre_cm2_s * t_pre_s / np.pi)
    return (Q / np.sqrt(np.pi * L_drive_cm2)) * np.exp(-(x_cm ** 2) / (4.0 * L_drive_cm2))

def format_sci(val, digits=3):
    if val is None:
        return "None"
    return f"{val:.{digits}e}"

def integrate_to_depth(x_cm, y, x_end_cm):
    if x_end_cm is None:
        return None

    if x_end_cm <= x_cm[0]:
        return 0.0

    if x_end_cm >= x_cm[-1]:
        return np.trapz(y, x_cm)

    i = np.searchsorted(x_cm, x_end_cm)

    x_part = np.concatenate([x_cm[:i], [x_end_cm]])
    y_end = np.interp(x_end_cm, x_cm, y)
    y_part = np.concatenate([y[:i], [y_end]])

    return np.trapz(y_part, x_part)

def first_junction_depth_cm(x_cm, ND_cm3, NA_cm3):
    """
    Finds first depth where net doping changes sign.
    Returns:
      xj_cm
      surface_polarity = "n", "p", or None
    """
    net = np.asarray(ND_cm3) - np.asarray(NA_cm3)

    if net[0] > 0:
        polarity = "n"
        idx = np.where(net <= 0)[0]
    elif net[0] < 0:
        polarity = "p"
        idx = np.where(net >= 0)[0]
    else:
        nz = np.where(np.abs(net) > 0)[0]
        if len(nz) == 0:
            return None, None
        if net[nz[0]] > 0:
            polarity = "n"
            idx = np.where(net <= 0)[0]
        else:
            polarity = "p"
            idx = np.where(net >= 0)[0]

    if len(idx) == 0:
        return None, polarity

    i = idx[0]
    if i == 0:
        return x_cm[0], polarity

    x1, x2 = x_cm[i - 1], x_cm[i]
    y1, y2 = net[i - 1], net[i]
    if y2 == y1:
        return x1, polarity

    xj = x1 + (0.0 - y1) * (x2 - x1) / (y2 - y1)
    return xj, polarity

def mobility_cm2_Vs(total_ionized_cm3, carrier_type):
    N = np.maximum(np.asarray(total_ionized_cm3, dtype=float), 1.0)

    if MOBILITY_MODEL == "constant":
        if carrier_type == "n":
            return np.full_like(N, MU_N_CONST_CM2_VS)
        return np.full_like(N, MU_P_CONST_CM2_VS)

    if MOBILITY_MODEL == "caughey_thomas":
        p = CT_PARAMS[carrier_type]
        return p["mu_min"] + (p["mu_max"] - p["mu_min"]) / (1.0 + (N / p["Nref"]) ** p["alpha"])

    raise ValueError(f"Unknown MOBILITY_MODEL: {MOBILITY_MODEL}")

def compute_sheet_resistance(x_cm, ND_cm3, NA_cm3, x_end_cm, surface_polarity):
    if x_end_cm is None or surface_polarity is None:
        return None, None, None, None

    ND = np.asarray(ND_cm3, dtype=float)
    NA = np.asarray(NA_cm3, dtype=float)
    total_ionized = ND + NA

    if surface_polarity == "n":
        majority = np.maximum(ND - NA, 0.0)
        mu = mobility_cm2_Vs(total_ionized, "n")
    else:
        majority = np.maximum(NA - ND, 0.0)
        mu = mobility_cm2_Vs(total_ionized, "p")

    sigma = Q_E * mu * majority
    Gsheet = integrate_to_depth(x_cm, sigma, x_end_cm)
    carrier_dose = integrate_to_depth(x_cm, majority, x_end_cm)

    if Gsheet is None or Gsheet <= 0:
        return None, Gsheet, carrier_dose, None

    Rs = 1.0 / Gsheet
    mu_eff = Gsheet / (Q_E * carrier_dose) if carrier_dose is not None and carrier_dose > 0 else None
    return Rs, Gsheet, carrier_dose, mu_eff

