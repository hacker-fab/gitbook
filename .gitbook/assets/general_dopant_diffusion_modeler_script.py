def solve_tridiagonal(a, b, c, d):
    n = len(b)
    ac = a.astype(float).copy()
    bc = b.astype(float).copy()
    cc = c.astype(float).copy()
    dc = d.astype(float).copy()

    for i in range(1, n):
        m = ac[i - 1] / bc[i - 1]
        bc[i] -= m * cc[i - 1]
        dc[i] -= m * dc[i - 1]

    x = np.zeros(n, dtype=float)
    x[-1] = dc[-1] / bc[-1]

    for i in range(n - 2, -1, -1):
        x[i] = (dc[i] - cc[i] * x[i + 1]) / bc[i]

    return x

def diffuse_one_species_implicit(profile_cm3, D_cm2_s, total_time_s, dx_cm,
                                 source_present=False, surface_concentration_cm3=None,
                                 r_target=0.5):
    C = np.asarray(profile_cm3, dtype=float).copy()
    n = C.size

    if total_time_s <= 0 or D_cm2_s <= 0:
        if source_present and surface_concentration_cm3 is not None:
            C[0] = surface_concentration_cm3
        return C

    n_sub = max(1, int(np.ceil(D_cm2_s * total_time_s / (r_target * dx_cm * dx_cm))))
    dt_s = total_time_s / n_sub
    r = D_cm2_s * dt_s / (dx_cm * dx_cm)

    a = np.zeros(n - 1, dtype=float)
    b = np.zeros(n, dtype=float)
    c = np.zeros(n - 1, dtype=float)

    if source_present:
        b[0] = 1.0
        c[0] = 0.0
    else:
        b[0] = 1.0 + 2.0 * r
        c[0] = -2.0 * r

    for i in range(1, n - 1):
        a[i - 1] = -r
        b[i] = 1.0 + 2.0 * r
        c[i] = -r

    a[-1] = -2.0 * r
    b[-1] = 1.0 + 2.0 * r

    for _ in range(n_sub):
        rhs = C.copy()
        if source_present:
            rhs[0] = surface_concentration_cm3
        C = solve_tridiagonal(a, b, c, rhs)
        C = np.maximum(C, 0.0)

    return C

def build_history_numeric(x_cm, steps, background_dopant, background_conc_cm3):
    dx_cm = x_cm[1] - x_cm[0]

    phosphorus = np.zeros_like(x_cm)
    boron = np.zeros_like(x_cm)

    if background_dopant == "boron":
        boron[:] = background_conc_cm3
    else:
        phosphorus[:] = background_conc_cm3

    history = [{
        "name": "Initial",
        "phosphorus": phosphorus.copy(),
        "boron": boron.copy(),
    }]

    for step in steps:
        temp_C = float(step["temp_C"])
        time_s = float(step["time_min"]) * 60.0
        source_dopant = step.get("source_dopant", None)
        source_conc = step.get("surface_concentration_cm3", None)

        Dp = diffusivity_cm2_s("phosphorus", temp_C)
        Db = diffusivity_cm2_s("boron", temp_C)

        phosphorus = diffuse_one_species_implicit(
            phosphorus, Dp, time_s, dx_cm,
            source_present=(source_dopant == "phosphorus"),
            surface_concentration_cm3=source_conc if source_dopant == "phosphorus" else None
        )

        boron = diffuse_one_species_implicit(
            boron, Db, time_s, dx_cm,
            source_present=(source_dopant == "boron"),
            surface_concentration_cm3=source_conc if source_dopant == "boron" else None
        )

        history.append({
            "name": step["name"],
            "phosphorus": phosphorus.copy(),
            "boron": boron.copy(),
        })

    return history

