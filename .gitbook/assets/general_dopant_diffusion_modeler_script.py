def make_x_grid(engine, wafer_thickness_um):
    """
    Analytic mode:
      dense near-surface grid + coarser deep grid
    Numeric mode:
      uniform grid (required by the FD solver)
    """
    if engine == "analytic":
        fine_um = min(FINE_REGION_UM, wafer_thickness_um)

        if fine_um >= wafer_thickness_um:
            x_um = np.linspace(0.0, wafer_thickness_um, NUM_FINE_POINTS)
        else:
            x_fine = np.linspace(0.0, fine_um, NUM_FINE_POINTS, endpoint=False)
            x_coarse = np.linspace(fine_um, wafer_thickness_um, NUM_COARSE_POINTS)
            x_um = np.unique(np.concatenate([x_fine, x_coarse]))
    else:
        x_um = np.linspace(0.0, wafer_thickness_um, NUM_POINTS_UNIFORM)

    return x_um * 1e-4, x_um

