def build_process_summary_lines(processes, background_dopant, background_conc_cm3):
    """Build compact plot text describing every compared process and constants."""
    lines = [
        "DIFFUSION STEP SUMMARY",
        f"Background: {background_dopant.title()}, {format_sci(background_conc_cm3, 2)} cm$^{{-3}}$",
    ]

    for process_index, process in enumerate(processes, start=1):
        process_name = process.get("name", f"Process {process_index}")
        steps = process.get("steps", [])
        lines.append(f"{process_index}. {process_name}")

        if not steps:
            lines.append("    No diffusion steps")
            continue

        for step_index, step in enumerate(steps, start=1):
            temp_C = float(step["temp_C"])
            time_min = float(step["time_min"])
            source = step.get("source_dopant", None)

            if source is None:
                lines.append(
                    f"    {step_index}) Drive-in: {temp_C:g} C, {time_min:g} min"
                )
            else:
                Cs = step.get("surface_concentration_cm3", None)
                source_label = "P" if source.lower() == "phosphorus" else "B"
                lines.append(
                    f"    {step_index}) {source_label} predep: {temp_C:g} C, "
                    f"{time_min:g} min, Cs={format_sci(Cs, 2)} cm$^{{-3}}$"
                )

    P = DOPANT_DATABASE["phosphorus"]
    B = DOPANT_DATABASE["boron"]
    lines.extend([
        f"P: D0={format_sci(P['D0_cm2_per_s'], 2)} cm$^2$/s, Ea={P['Ea_eV']:.2f} eV",
        f"B: D0={format_sci(B['D0_cm2_per_s'], 2)} cm$^2$/s, Ea={B['Ea_eV']:.2f} eV",
    ])
    return lines


