# General 1D dopant diffusion simulator for silicon.
#
# Features:
#   - Choose background dopant type and concentration
#   - Compare multiple independently defined diffusion processes on one plot
#   - Program an arbitrary number of diffusion steps within each process
#   - Each step can be:
#       * predep  (source_dopant = "boron" or "phosphorus")
#       * drive-in (source_dopant = None)
#   - One comparison plot containing the final profiles from every process
#   - Can use either:
#       * analytic engine: rigid erfc predep + Gaussian redistribution
#       * numeric engine: implicit finite-difference solver
#   - Calculates final Rs from:
#       * x = 0 to x = xj if a junction exists
#       * x = 0 to wafer thickness if no junction exists
#   - Background is part of the initial condition, so same-type diffusion
#     naturally gives one total species curve that relaxes toward the background
#
# Notes:
#   - Analytic mode assumes a semi-infinite substrate and uses erfc/Gaussian
#     as an engineering superposition model across multiple steps.
#   - Numeric mode uses a finite wafer thickness and zero-flux backside boundary.
#   - One source dopant per step (or no source).

