def species_profile_after_step_analytic(x_cm, species, step_end_idx, steps,
                                        background_dopant, background_conc_cm3):
    """
    Semi-infinite analytic superposition model.

    For each source-present step of this species:
      - if there is no later thermal budget up to step_end_idx:
            contribution = erfc predep
      - if there is later thermal budget:
            contribution = Gaussian redistribution of that predep dose

    All contributions are summed on top of the constant background
    if the background species matches.
    """
    total = np.zeros_like(x_cm)
    if background_dopant == species:
        total += background_conc_cm3

    for i in range(step_end_idx + 1):
        step_i = steps[i]
        if step_i.get("source_dopant", None) != species:
            continue

        T_pre = float(step_i["temp_C"])
        t_pre_s = float(step_i["time_min"]) * 60.0
        Cs = float(step_i["surface_concentration_cm3"])
        D_pre = diffusivity_cm2_s(species, T_pre)

        # cumulative later thermal budget
        L_drive = 0.0
        for k in range(i + 1, step_end_idx + 1):
            T_k = float(steps[k]["temp_C"])
            t_k_s = float(steps[k]["time_min"]) * 60.0
            D_k = diffusivity_cm2_s(species, T_k)
            L_drive += D_k * t_k_s

        if L_drive > 0:
            contrib = gaussian_from_predep_cm3(x_cm, Cs, D_pre, t_pre_s, L_drive)
        else:
            contrib = predep_erfc_profile_cm3(x_cm, Cs, D_pre, t_pre_s)

        total += contrib

    return total

def build_history_analytic(x_cm, steps, background_dopant, background_conc_cm3):
    history = []

    P0 = np.zeros_like(x_cm)
    B0 = np.zeros_like(x_cm)
    if background_dopant == "boron":
        B0[:] = background_conc_cm3
    else:
        P0[:] = background_conc_cm3

    history.append({
        "name": "Initial",
        "phosphorus": P0.copy(),
        "boron": B0.copy(),
    })

    for end_idx in range(len(steps)):
        P = species_profile_after_step_analytic(
            x_cm, "phosphorus", end_idx, steps, background_dopant, background_conc_cm3
        )
        B = species_profile_after_step_analytic(
            x_cm, "boron", end_idx, steps, background_dopant, background_conc_cm3
        )
        history.append({
            "name": steps[end_idx]["name"],
            "phosphorus": P,
            "boron": B,
        })

    return history

