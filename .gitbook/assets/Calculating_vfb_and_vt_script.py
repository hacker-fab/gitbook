# Print example values
# ==========================================
print('========================================')
print(f'Substrate type: {substrate_type}')
print(f'Device interpretation: {device_label}')
print(f'At N = {N_example:.2e} cm^-3:')
print(f'  phi_F = {phi_F_ex:.4f} V')
print(f'  phi_s = {phi_s_ex:.4f} eV')
print(f'  V_FB  = {Vfb_ex:.4f} V')
print('----------------------------------------')

